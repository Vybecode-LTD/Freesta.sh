"""Credits and ledger exports: ATTRIBUTION.md, credits HTML snippet, CSV."""

from __future__ import annotations

import csv
import io
from collections import defaultdict
from datetime import UTC, datetime
from html import escape

from freestash.models import LedgerEntry, Tier


def attribution_markdown(entries: list[LedgerEntry], project: str | None = None) -> str:
    title = f"# Asset credits — {project}" if project else "# Asset credits"
    lines = [title, "", f"_Generated by Freestash on {datetime.now(UTC):%Y-%m-%d}. {len(entries)} asset(s)._", ""]
    by_license: dict[str, list[LedgerEntry]] = defaultdict(list)
    for e in entries:
        by_license[e.license_label].append(e)
    for label in sorted(by_license, key=lambda k: (not by_license[k][0].license_id.startswith(("CC0", "PD", "PDM", "NOC")), k)):
        group = by_license[label]
        url = group[0].license_url
        lines += [f"## {label}" + (f" — <{url}>" if url else ""), ""]
        for e in sorted(group, key=lambda x: x.title.lower()):
            lines.append(f"- {e.attribution or e.title}" + (f" — <{e.landing_url}>" if e.landing_url and e.landing_url not in (e.attribution or "") else ""))
        lines.append("")
    flagged = [e for e in entries if e.tier != Tier.GREEN]
    if flagged:
        lines += ["## Needs review", "", "These were not GREEN for their use case when retrieved:", ""]
        lines += [f"- **{e.title}** ({e.tier.value}, {e.use_case.value}) — {e.landing_url or e.asset_uid}" for e in flagged]
        lines.append("")
    return "\n".join(lines)


def credits_html(entries: list[LedgerEntry]) -> str:
    items = []
    for e in sorted(entries, key=lambda x: x.title.lower()):
        title = escape(e.title)
        link = f'<a href="{escape(e.landing_url)}">{title}</a>' if e.landing_url else title
        by = f" by {escape(e.creator)}" if e.creator else ""
        lic = f'<a href="{escape(e.license_url)}">{escape(e.license_label)}</a>' if e.license_url else escape(e.license_label)
        items.append(f"  <li>{link}{by} — {lic}</li>")
    return '<ul class="asset-credits">\n' + "\n".join(items) + "\n</ul>\n"


LEDGER_COLUMNS = ["retrieved_at", "project", "title", "creator", "provider", "asset_uid", "license_id", "license_label",
                  "license_url", "trust", "use_case", "tier", "landing_url", "file_url", "sha256", "local_path", "attribution"]


def ledger_csv(entries: list[LedgerEntry]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=LEDGER_COLUMNS, extrasaction="ignore")
    w.writeheader()
    for e in entries:
        row = e.model_dump(mode="json")
        w.writerow({k: row.get(k) for k in LEDGER_COLUMNS})
    return buf.getvalue()
