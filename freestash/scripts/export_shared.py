"""Write the files both apps share from one definition each (run after changing either source).

    python scripts/export_shared.py          # rewrite the generated files
    python scripts/export_shared.py --check  # exit 1 if any is out of date (CI)

Sources -> outputs:
    src/freestash/providers/keys.py   -> shared/provider-keys.json (the desktop's offline copy of the key help)
    shared/design-tokens.json         -> web/src/tokens.css + the desktop's Services/DesignTokens.g.cs
    shared/categories.json            -> src/freestash/categories_data.py (the query words), web/src/lib/categories.ts
                                         + the desktop's Freestash.Client/Categories.g.cs (ids, labels, order)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from freestash.providers.keys import KEY_CATALOG

REPO = Path(__file__).resolve().parents[2]
SHARED = REPO / "shared"
WEB_TOKENS = REPO / "freestash" / "web" / "src" / "tokens.css"
DESKTOP_TOKENS = REPO / "freestash-desktop" / "src" / "Freestash.Desktop" / "Services" / "DesignTokens.g.cs"
ENGINE_CATEGORIES = REPO / "freestash" / "src" / "freestash" / "categories_data.py"
WEB_CATEGORIES = REPO / "freestash" / "web" / "src" / "lib" / "categories.ts"
DESKTOP_CATEGORIES = REPO / "freestash-desktop" / "src" / "Freestash.Client" / "Categories.g.cs"
BANNER = "GENERATED from shared/design-tokens.json by freestash/scripts/export_shared.py. Don't edit; edit the JSON."
CAT_BANNER = "GENERATED from shared/categories.json by freestash/scripts/export_shared.py. Don't edit; edit the JSON."


def _kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def _alpha(hex6: str, alpha: float) -> str:
    return f"{hex6[:7]}{round(alpha * 255):02X}"


def _argb(hex_: str) -> str:
    """#RRGGBB[AA] (CSS order) -> #AARRGGBB (Avalonia order)."""
    hex_ = hex_.upper()
    return f"#{hex_[7:9] or 'FF'}{hex_[1:7]}"


def tokens_css(t: dict) -> str:
    out = [f"/* {BANNER} */", ""]
    for theme, sel in (("dark", ':root, [data-theme="dark"]'), ("light", '[data-theme="light"]')):
        out.append(f"{sel} {{")
        out.append(f"  color-scheme: {theme};")
        out += [f"  --{_kebab(k)}: {v};" for k, v in t["themes"][theme].items()]
        out.append(f"  --accent-text: var(--accent-text-{theme});")
        out.append("}")
    out.append("")
    for i, (name, a) in enumerate(t["accents"].items()):
        sel = f':root, [data-accent="{name}"]' if i == 0 else f'[data-accent="{name}"]'
        out.append(f"{sel} {{ --accent: {a['fill']}; --on-accent: {a['on']}; --accent-text-dark: {a['textDark']}; "
                   f"--accent-text-light: {a['textLight']}; --accent-soft: {_alpha(a['fill'], 0.12)}; "
                   f"--accent-line: {_alpha(a['fill'], 0.55)}; }}")
    out.append("")
    r = t["radius"]
    out.append(":root {")
    out += [f"  --r-{k}: {v}px;" for k, v in r.items()]
    out.append(f"  --sans: \"{t['fonts']['sans']} Variable\", \"{t['fonts']['sans']}\", system-ui, sans-serif;")
    out.append(f"  --mono: \"{t['fonts']['mono']} Variable\", \"{t['fonts']['mono']}\", ui-monospace, monospace;")
    out.append("}")
    return "\n".join(out) + "\n"


def tokens_cs(t: dict) -> str:
    def palette(theme: str) -> str:
        rows = ",\n".join(f'        ["{k}"] = "{_argb(v)}"' for k, v in t["themes"][theme].items())
        return f"    public static readonly IReadOnlyDictionary<string, string> {theme.capitalize()} = new Dictionary<string, string>\n    {{\n{rows},\n    }};"

    accents = ",\n".join(
        f'        ["{n}"] = new("{_argb(a["fill"])}", "{_argb(a["textDark"])}", "{_argb(a["textLight"])}", "{_argb(a["on"])}")'
        for n, a in t["accents"].items())
    radius = "\n".join(f"    public const double Radius{k.capitalize()} = {v};" for k, v in t["radius"].items())
    return (f"// <auto-generated>{BANNER}</auto-generated>\n"
            "namespace Freestash.Desktop.Services;\n\n"
            "public sealed record AccentTokens(string Fill, string TextDark, string TextLight, string On);\n\n"
            f"/// <summary>The {t['name']} design tokens, shared with the web app (see shared/design-tokens.json).</summary>\n"
            "public static class DesignTokens\n{\n"
            f"{palette('dark')}\n\n{palette('light')}\n\n"
            "    public static readonly IReadOnlyDictionary<string, AccentTokens> Accents = new Dictionary<string, AccentTokens>\n"
            f"    {{\n{accents},\n    }};\n\n{radius}\n}}\n")


def _wrap_items(items: list[str], indent: int, width: int = 100) -> list[str]:
    """Comma-separated items over as few lines as fit, never splitting one (a phrase has spaces)."""
    lines: list[str] = []
    for item in items:
        if lines and len(lines[-1]) + len(item) + 2 <= width:
            lines[-1] += f" {item},"
        else:
            lines.append(" " * indent + f"{item},")
    return lines


def categories_py(data: dict) -> str:
    out = [f'"""{CAT_BANNER}"""', "", "CATEGORIES: list[dict] = ["]
    for c in data["categories"]:
        out += ["    {", f'        "id": {json.dumps(c["id"])},', f'        "label": {json.dumps(c["label"])},',
                '        "words": [', *_wrap_items([json.dumps(w, ensure_ascii=False) for w in c["words"]], 12),
                "        ],", "    },"]
    out += ["]", "", '# Words that turn packs on ("sfx pack")', "PACK_WORDS: list[str] = [",
            *_wrap_items([json.dumps(w, ensure_ascii=False) for w in data["pack_words"]], 4), "]"]
    return "\n".join(out) + "\n"


def _ts_preset(p: dict) -> str:
    media = ", ".join(json.dumps(m) for m in p["media"])
    return (f'  {{ id: {json.dumps(p["id"])}, label: {json.dumps(p["label"])}, hint: {json.dumps(p["hint"])},\n'
            f'    media: [{media}], packs: {json.dumps(p["packs"])} }},')


def _cs_preset(p: dict) -> str:
    media = ", ".join(f"MediaType.{m.capitalize()}" for m in p["media"])
    return (f'        new({json.dumps(p["id"])}, {json.dumps(p["label"])}, {json.dumps(p["hint"])},\n'
            f'            [{media}], {json.dumps(p["packs"])}),')


def categories_ts(data: dict) -> str:
    rows = "\n".join(f'  {{ id: "{c["id"]}", label: {json.dumps(c["label"])} }},' for c in data["categories"])
    presets = "\n".join(_ts_preset(p) for p in data["presets"])
    return (f"// {CAT_BANNER}\n"
            'import type { MediaType } from "./types";\n\n'
            "/** The result categories in display order: the Media filter, the sections and the jump bar. */\n"
            f"export const CATEGORIES: readonly {{ id: MediaType; label: string }}[] = [\n{rows}\n];\n\n"
            '/** One-click media selections ("Game assets"); `packs` turns the Packs switch on too. */\n'
            "export const PRESETS: readonly { id: string; label: string; hint: string; media: readonly MediaType[]; "
            f"packs: boolean }}[] = [\n{presets}\n];\n")


def categories_cs(data: dict) -> str:
    rows = "\n".join(f'        new(MediaType.{c["id"].capitalize()}, {json.dumps(c["label"])}),' for c in data["categories"])
    presets = "\n".join(_cs_preset(p) for p in data["presets"])
    return (f"// <auto-generated>{CAT_BANNER}</auto-generated>\n"
            "namespace Freestash.Client;\n\n"
            "public sealed record Category(MediaType Id, string Label);\n\n"
            '/// <summary>A one-click media selection ("Game assets"); <c>Packs</c> turns the Packs switch on too.</summary>\n'
            "public sealed record Preset(string Id, string Label, string Hint, IReadOnlyList<MediaType> Media, bool Packs);\n\n"
            "/// <summary>The result categories in display order, shared with the web app (shared/categories.json).</summary>\n"
            "public static class Categories\n{\n"
            f"    public static readonly IReadOnlyList<Category> All =\n    [\n{rows}\n    ];\n\n"
            f"    public static readonly IReadOnlyList<Preset> Presets =\n    [\n{presets}\n    ];\n}}\n")


def outputs() -> dict[Path, str]:
    keys = json.dumps([k.as_json() for k in KEY_CATALOG], indent=2, ensure_ascii=False) + "\n"
    tokens = json.loads((SHARED / "design-tokens.json").read_text(encoding="utf-8"))
    cats = json.loads((SHARED / "categories.json").read_text(encoding="utf-8"))
    return {SHARED / "provider-keys.json": keys, WEB_TOKENS: tokens_css(tokens), DESKTOP_TOKENS: tokens_cs(tokens),
            ENGINE_CATEGORIES: categories_py(cats), WEB_CATEGORIES: categories_ts(cats),
            DESKTOP_CATEGORIES: categories_cs(cats)}


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, body in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == body:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body, encoding="utf-8", newline="\n")
    for p in stale:
        print(("STALE " if check else "wrote ") + str(p.relative_to(REPO)))
    return 1 if check and stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
